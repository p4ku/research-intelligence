import uuid
from django.db import models
from .session import PaperChatSession


class PaperChatMessage(models.Model):
    """
    Represents an individual message turn within a PaperChatSession.
    Supports asynchronous Celery generation tracking, visual grounding, deep thinking, hallucination guards,
    and granular per-message token / USD cost accounting.
    """
    SENDER_CHOICES = [
        ('user', 'User'),
        ('assistant', 'Assistant / Gemini'),
    ]
    STATUS_CHOICES = [
        ('pending', 'Pending'),
        ('processing', 'Processing'),
        ('completed', 'Completed'),
        ('failed', 'Failed'),
        # The reader stopped the stream (or the tab went away) part-way: the
        # text that had arrived is kept and billed, unlike a failure.
        ('aborted', 'Aborted'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    session = models.ForeignKey(PaperChatSession, on_delete=models.CASCADE, related_name="messages")
    sender = models.CharField(max_length=20, choices=SENDER_CHOICES, default='user')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='pending')
    deep_thinking = models.BooleanField(default=False, help_text="Whether deep thinking scratchpad reasoning was enabled")
    thinking_process = models.TextField(blank=True, default="", help_text="Internal model reasoning trace / thoughts when deep_thinking is enabled")
    llm_model = models.CharField(max_length=100, blank=True, default="", help_text="LLM model used for generating this turn")
    
    question = models.TextField(blank=True, default="", help_text="Original prompt submitted by the user")
    message = models.TextField(blank=True, default="", help_text="Response generated by the AI assistant or user prompt")
    citations = models.JSONField(default=list, blank=True, help_text="Referenced evidence quotes, paper sections, or parameter definitions")
    visual_citations = models.JSONField(default=list, blank=True, help_text="List of citations with page number, box_2d coordinates, and labels")
    hallucination_guard = models.JSONField(default=dict, blank=True, help_text="Deterministic grounding verification audit score and metrics")
    
    celery_task_id = models.CharField(max_length=255, blank=True, null=True)
    tokens_in = models.IntegerField(default=0, help_text="Input/prompt tokens consumed by this message")
    tokens_out = models.IntegerField(default=0, help_text="Output/candidate tokens generated for this message")
    total_tokens = models.IntegerField(default=0, help_text="Total tokens (in + out) consumed by this message")
    usd_cost = models.DecimalField(max_digits=10, decimal_places=5, default=0.0, help_text="Estimated USD cost for this message")
    error_message = models.TextField(blank=True, null=True)
    
    created_at = models.DateTimeField(auto_now_add=True)
    completed_at = models.DateTimeField(blank=True, null=True)

    class Meta:
        app_label = 'chat'
        ordering = ['created_at']
        indexes = [
            models.Index(fields=['session', 'created_at']),
            models.Index(fields=['session', 'sender']),
            models.Index(fields=['status']),
        ]

    def __str__(self):
        return f"[{self.session_id}] {self.sender}: {self.message[:40]}... ({self.status})"
